interface FenceIdentifier {
  name: string;
  position: DocFinding['position'];
  line: string;
  /** Immediate object-literal property that owns a dictionary entry, never an arbitrary ancestor. */
  container?: string;
}

/**
 * Identifiers a fence asserts as library API.
 *
 * Only the positions that make a claim about a contract are read. A local `const p = normalCdf(0)` is
 * the author's own variable and asserts nothing about the library, so plain variable declarations are
 * collected as LOCAL and excluded — as are types the fence declares for itself.
 */
function fenceIdentifiers(source: string): FenceIdentifier[] {
  const file = ts.createSourceFile('fence.ts', source, ts.ScriptTarget.ESNext, true);
  const lines = source.split('\n');
  const local = new Set<string>();
  const collectLocal = (node: ts.Node): void => {
    if (
      (ts.isInterfaceDeclaration(node) ||
        ts.isTypeAliasDeclaration(node) ||
        ts.isFunctionDeclaration(node) ||
        ts.isClassDeclaration(node)) &&
      node.name
    ) {
      local.add(node.name.text);
    }
    if (ts.isVariableDeclaration(node) && ts.isIdentifier(node.name)) local.add(node.name.text);
    ts.forEachChild(node, collectLocal);
  };
  collectLocal(file);

  const out: FenceIdentifier[] = [];
  const visit = (node: ts.Node): void => {
    let found: { name: string; position: DocFinding['position'] } | undefined;
    if (ts.isImportSpecifier(node)) {
      found = { name: (node.propertyName ?? node.name).text, position: 'import' };
    } else if (ts.isPropertyAccessExpression(node)) {
      const root = node.expression;
      if (!(ts.isIdentifier(root) && HOST_OBJECTS.has(root.text))) {
        found = { name: node.name.text, position: 'access' };
      }
    } else if (ts.isPropertyAssignment(node) && ts.isIdentifier(node.name)) {
      found = { name: node.name.text, position: 'field' };
    } else if (ts.isPropertySignature(node) && node.name && ts.isIdentifier(node.name)) {
      found = { name: node.name.text, position: 'declaration' };
    } else if (ts.isBindingElement(node)) {
      const bound =
        node.propertyName && ts.isIdentifier(node.propertyName)
          ? node.propertyName
          : ts.isIdentifier(node.name)
            ? node.name
            : undefined;
      if (bound) found = { name: bound.text, position: 'destructure' };
    }
    if (found && !LANGUAGE_MEMBERS.has(found.name) && !local.has(found.name)) {
      const line = file.getLineAndCharacterOfPosition(node.getStart(file)).line;
      const parent = node.parent?.parent;
      const container =
        ts.isPropertyAssignment(node) &&
        parent &&
        ts.isPropertyAssignment(parent) &&
        ts.isIdentifier(parent.name)
          ? parent.name.text
          : undefined;
      out.push({
        ...found,
        ...(container === undefined ? {} : { container }),
        line: (lines[line] ?? '').trim().slice(0, 110),
      });
    }
    ts.forEachChild(node, visit);
  };
  visit(file);
  return out;
}

function executableFences(text: string): { source: string; sourceHeading?: string }[] {
  const fences: { source: string; sourceHeading?: string }[] = [];
  let sourceHeading: string | undefined;
  // One linear scan: generated full docs contain thousands of source sections. A heading inside a
  // matched code fence is consumed with the fence, never interpreted as provenance.
  for (const match of text.matchAll(
    /^(#{1,3}) ([^\n]+)$|```(?:ts|typescript|js|javascript)\n([\s\S]*?)```/gm,
  )) {
    if (match[1] !== undefined) sourceHeading = match[1] === '###' ? match[2] : undefined;
    else
      fences.push({ source: match[3]!, ...(sourceHeading === undefined ? {} : { sourceHeading }) });
  }
  return fences;
}

export interface DocsInventory {
  version: number;
  summary: Record<string, unknown>;
  surfaces: DocSurface[];
  findings: DocFinding[];
  /** Dispositions that matched nothing — stale exemptions, which are themselves a defect. */
  unusedExceptions: string[];
}

export function documentationInventory(): DocsInventory {
  const shipped = shippedNames();
  const surfaces: DocSurface[] = [];
  const findings: DocFinding[] = [];
  const usedExceptions = new Set<string>();

  for (const path of documentationFiles()) {
    const text = readFileSync(path, 'utf8');
    const classified = classifyDocument(path, text);
    const rule = ruleFor(classified.class);
    const fences = executableFences(text);
    const relativePath = relative(ROOT, path);
    surfaces.push({
      path: relativePath,
      class: classified.class,
      owner: classified.owner,
      rule,
      codeFences: fences.length,
    });
    if (rule === 'none') continue;

    for (const fence of fences) {
      for (const identifier of fenceIdentifiers(fence.source)) {
        let forbidden: string[] | undefined;
        if (rule === 'truthfulness') {
          if (shipped.has(identifier.name)) continue;
        } else {
          const flagged = flaggedTokens(identifier.name);
          if (flagged.length === 0) continue;
          forbidden = flagged;
        }
        const id = `${relativePath}#${identifier.name}`;
        if (
          matchesDocumentedException({
            path: relativePath,
            owner: classified.owner,
            ...fence,
            identifier,
          })
        ) {
          usedExceptions.add(id);
          continue;
        }
        // One finding per (file, name) — the same stale field repeated eight times in one document is
        // one repair, and eight rows would just make the artifact harder to read.
        if (findings.some((existing) => existing.id === id)) continue;
        findings.push({
          id,
          path: relativePath,
          class: classified.class,
          rule,
          name: identifier.name,
          position: identifier.position,
          ...(forbidden ? { forbidden } : {}),
          line: identifier.line,
        });
      }
    }
  }

  surfaces.sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0));
  findings.sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));

  const byClass = surfaces.reduce<Record<string, number>>(
    (accumulator, surface) => {
      accumulator[surface.class] = (accumulator[surface.class] ?? 0) + 1;
      return accumulator;
    },
    Object.create(null) as Record<string, number>,
  );

  return {
    version: 1,
    summary: {
      surfaces: surfaces.length,
      byClass,
      executableFences: surfaces.reduce((total, surface) => total + surface.codeFences, 0),
      checkedUnderTruthfulness: surfaces.filter((surface) => surface.rule === 'truthfulness')
        .length,
      checkedUnderVocabulary: surfaces.filter((surface) => surface.rule === 'vocabulary').length,
      shippedNamesWatched: shipped.size,
      documentedExceptions: Object.keys(DOCUMENTED_EXCEPTIONS).length,
      findings: findings.length,
    },
    surfaces,
    findings,
    unusedExceptions: Object.keys(DOCUMENTED_EXCEPTIONS)
      .filter((id) => !usedExceptions.has(id))
      .sort(),
  };
}

export function readDocsInventory(): DocsInventory | null {
  try {
    return JSON.parse(readFileSync(DOCS_MANIFEST_PATH, 'utf8')) as DocsInventory;
  } catch {
    return null;
  }
}

export function writeDocsInventory(): DocsInventory {
  const inventory = documentationInventory();
  writeFileSync(DOCS_MANIFEST_PATH, `${JSON.stringify(inventory, null, 2)}\n`, 'utf8');
  return inventory;
}

const isMain = process.argv[1] && import.meta.url === new URL(`file://${process.argv[1]}`).href;
if (isMain) {
  const inventory = writeDocsInventory();
  const { summary } = inventory;
  console.log(
    `docs-inventory: ${summary['surfaces']} surfaces ` +
      `(${summary['checkedUnderTruthfulness']} truthfulness, ${summary['checkedUnderVocabulary']} vocabulary), ` +
      `${summary['executableFences']} executable fences, ${summary['findings']} findings`,
  );
  for (const finding of inventory.findings) {
    console.log(`  [${finding.rule}] ${finding.id} (${finding.position}) — ${finding.line}`);
  }
  if (inventory.unusedExceptions.length > 0) {
    console.log(`  STALE dispositions: ${inventory.unusedExceptions.join(', ')}`);
  }
}
