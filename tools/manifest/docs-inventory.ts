/**
 * Phase 3B.N8-DOCS — the documentation naming inventory.
 *
 * The code surface has been inventoried, classified and gated for a whole phase. Documentation had not
 * been, and it is part of the public contract: an example that teaches a field the library does not have
 * is the same class of defect as the wrong field itself, and it reaches the user first.
 *
 * Every documentation surface gets ONE class from the spec's table, because the required treatment
 * differs and a single rule would be wrong for most of them:
 *
 *   future-target       use final vocabulary NOW; a legacy token only inside a before→after explanation
 *   current-runnable    must be truthful against the executable baseline
 *   generated           fix the generator, then regenerate; hand-editing is not a closeout
 *   historical          preserve the exact old identity — it is evidence about what shipped
 *   formula-notation    conventional symbols stay in equations
 *   migration-evidence  before→after tables and search synonyms may name old terms
 *
 * Two rules follow from the classes, and the difference between them is the point of this module:
 *
 *   TRUTHFULNESS (current-runnable, generated) — every identifier a fence presents as library API must
 *     be a name the library actually exports. Checked against the 19,505-name naming baseline, which is
 *     ground truth rather than a heuristic. This is strictly stronger than a token rule in both
 *     directions: it convicts `var`/`iv`/`vols`, which tokenize innocently but do not exist, and it
 *     ACQUITS `k` and `w` in the SSVI fences, which a token rule flags and which are really shipped.
 *
 *   VOCABULARY (future-target) — a spec for unbuilt work is where the next generation of names is
 *     chosen, so it is held to the naming policy itself. There is no baseline to check against yet;
 *     the whole point is to keep `vol: number` from being implemented as `vol`.
 *
 * PROSE is not scanned under either rule. A sentence may say "VaR" or "the ATM vol" — that is how the
 * subject is written, and 3B.N normalized executable identities, never English. Only fenced `ts`/`js`
 * blocks are read, and within them only the positions that assert an API shape.
 *
 * The classes are derived from location and from each document's own declared status, never from a
 * hand-kept list, so a new document is classified the moment it exists. Findings that are legitimate
 * carry an explicit machine-readable disposition in {@link DOCUMENTED_EXCEPTIONS} — the spec rules out a
 * broad file allowlist, and a per-finding entry is what replaces it. A disposition that stops matching
 * anything is itself a failure, so the escape hatch cannot quietly rot into an allowlist.
 */

