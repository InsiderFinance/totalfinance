/** The spec's surface classes, verbatim. */
export type DocClass =
  | 'future-target'
  | 'current-runnable'
  | 'generated'
  | 'historical'
  | 'formula-notation'
  | 'migration-evidence';

/** Which rule a class is held to. */
export type DocRule = 'truthfulness' | 'vocabulary' | 'none';

export function ruleFor(documentClass: DocClass): DocRule {
  switch (documentClass) {
    case 'current-runnable':
    case 'generated':
      return 'truthfulness';
    case 'future-target':
      return 'vocabulary';
    // Historical records, before→after tables and equation notation are all cases where naming an old
    // or conventional identity is the document's JOB.
    default:
      return 'none';
  }
}

export interface DocSurface {
  path: string;
  class: DocClass;
  /** The generator that owns it, or `human` — one or the other, never neither. */
  owner: string;
  rule: DocRule;
  /** Fenced ts/js blocks: the executable part of a document. */
  codeFences: number;
}

export interface DocFinding {
  /** Stable identity, so a disposition can name one finding rather than exempting a whole file. */
  id: string;
  path: string;
  class: DocClass;
  rule: DocRule;
  name: string;
  /** Where in the fence the name is asserted as API. */
  position: 'import' | 'access' | 'field' | 'declaration' | 'destructure';
  /** For `vocabulary` findings: the forbidden tokens the name carries. */
  forbidden?: string[];
  /** The fence line, trimmed. */
  line: string;
}

