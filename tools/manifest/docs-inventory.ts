/** A generated-source disposition never exempts the same spelling in another API or position. */
export function matchesDocumentedException(input: {
  path: string;
  owner: string;
  sourceHeading?: string;
  identifier: FenceIdentifier;
}): boolean {
  const entry = DOCUMENTED_EXCEPTIONS[`${input.path}#${input.identifier.name}`];
  if (!entry) return false;
  const scope = entry.generatedSource;
  if (!scope) return true;
  return (
    input.owner === scope.owner &&
    scope.headings.map(toPublicSpecifier).includes(input.sourceHeading ?? '') &&
    input.identifier.position === scope.position &&
    (scope.containers === undefined ||
      scope.containers.includes(input.identifier.container ?? '')) &&
    (scope.line === undefined || scope.line === input.identifier.line)
  );
}

/** Every markdown/text documentation file, plus the package READMEs. */
function documentationFiles(): string[] {
  const out: string[] = [];
  const walk = (dir: string): void => {
    for (const entry of readdirSync(dir).sort()) {
      const path = resolve(dir, entry);
      if (statSync(path).isDirectory()) walk(path);
      else if (entry.endsWith('.md') || entry.endsWith('.txt')) out.push(path);
    }
  };
  walk(resolve(ROOT, 'docs'));
  const packages = resolve(ROOT, 'packages');
  for (const dir of readdirSync(packages).sort()) {
    const readme = resolve(packages, dir, 'README.md');
    if (existsSync(readme)) out.push(readme);
    // The API reports are generated consumer material that item 4 names explicitly, and the walk
    // did not reach them — 15 generated documents outside the inventory entirely.
    const etc = resolve(packages, dir, 'etc');
    if (existsSync(etc)) {
      for (const entry of readdirSync(etc).sort()) {
        if (entry.endsWith('.api.md')) out.push(resolve(etc, entry));
      }
    }
  }
  const rootReadme = resolve(ROOT, 'README.md');
  if (existsSync(rootReadme)) out.push(rootReadme);
  return out;
}

/**
 * Does this spec declare the work SHIPPED?
 *
 * The status sits in a markdown blockquote, so it wraps: five specs write `Status:` at the end of one
 * line and `> **shipped** as ...` on the next, and one writes `**shipped in two waves.**`. Matching the
 * raw text missed all six and quietly held live API documentation to the weaker rule — so the
 * blockquote markers and line breaks are normalized away before looking.
 */
function declaresShipped(text: string): boolean {
  const flattened = text
    .split('\n')
    .map((line) => line.replace(/^\s*>\s?/, ''))
    .join(' ');
  return /Status:\s*\*\*shipped\b/i.test(flattened);
}

/** Classify one surface and name its owner. */
export function classifyDocument(path: string, text: string): { class: DocClass; owner: string } {
  const relativePath = relative(ROOT, path);

  // Generated material is DECLARED, in `tools/generated-docs.ts`, because inferring it did not work:
  // a `<!-- Generated by … -->` marker missed three TA references that emit none and one that writes
  // it in capitals, and attributed all four to a human owner.
  const declaredOwner = ownerOfGenerated(relativePath);
  if (declaredOwner) return { class: 'generated', owner: declaredOwner };

  // A marker still counts, for a generator that has not been added to the registry yet — but the
  // registry gate treats that as a failure rather than a fallback.
  const generatedBy = /^<!--\s*generated by ([^\s]+)/im.exec(text);
  if (generatedBy) return { class: 'generated', owner: generatedBy[1]! };

  // A completed milestone is evidence about what shipped and is never silently rewritten.
  if (relativePath.includes('/milestones/')) return { class: 'historical', owner: 'human' };
  // The naming spec and the decision ledger ARE the before→after record.
  if (/phase-3b-(?:public-naming|decision-ledger)/.test(relativePath)) {
    return { class: 'migration-evidence', owner: 'human' };
  }
  if (relativePath.includes('/formulas/')) return { class: 'formula-notation', owner: 'human' };

  // A spec that declares itself SHIPPED documents a callable API, so its fences are runnable guidance
  // and must be truthful. An unshipped spec is where the next names are chosen, so it is held to the
  // vocabulary instead. Read from the document's own status line rather than from a list.
  if (relativePath.includes('/specs/')) {
    return declaresShipped(text)
      ? { class: 'current-runnable', owner: 'human' }
      : { class: 'future-target', owner: 'human' };
  }

  if (
    relativePath.includes('/guides/') ||
    relativePath.includes('/examples/') ||
    /(?:^|\/)README\.md$/.test(relativePath) ||
    /getting-started\.md$/.test(relativePath)
  ) {
    return { class: 'current-runnable', owner: 'human' };
  }
  return { class: 'future-target', owner: 'human' };
}

/** Every public name the library actually exports — ground truth for the truthfulness rule. */
function shippedNames(): Set<string> {
  const manifest = JSON.parse(
    readFileSync(resolve(ROOT, 'tools/manifest/public-naming.json'), 'utf8'),
  ) as { identities: { name: string }[] };
  return new Set(manifest.identities.map((identity) => identity.name));
}

