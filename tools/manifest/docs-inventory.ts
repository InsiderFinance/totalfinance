/**
 * Generated path → owning generator, declared in `tools/generated-docs.ts`.
 *
 * Memoized because building it imports every generator. Reading a declared registry replaces what
 * used to be a `<!-- Generated by … -->` marker guess, which missed four of the twenty-one generated
 * documents — three TA references emit no marker, and `talib-coverage.md` writes it in capitals.
 */
let generatedOwners: Map<string, string> | null = null;
function ownerOfGenerated(relativePath: string): string | undefined {
  generatedOwners ??= generatedDocOwners();
  return generatedOwners.get(relativePath);
}

const ROOT = fileURLToPath(new URL('../../', import.meta.url));

